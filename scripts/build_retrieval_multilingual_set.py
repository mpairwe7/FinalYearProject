"""Build the trilingual retrieval benchmark (``evals/retrieval_multilingual``).

Every query carries the ids of the Qdrant points that answer it, so retrieval
can be scored as retrieval (Hit@1, MRR, nDCG) rather than through a generated
reply. Four sets:

``faq``       A stratified sample of the indexed FAQ rows (at most
              ``--per-file`` per source file). Each row is asked as written
              (``en_verbatim``), as a taxpayer would put it (``en_paraphrase``),
              and as that paraphrase in Luganda and Swahili, plain and
              code-switched. The gold is every point whose question is the
              same text, so a row repeated across files is not a miss.
``native``    The rows whose Luganda and Swahili questions were written into
              the corpus itself (``question_lg`` / ``question_sw``). They are
              the control for the next caveat.
``coverage``  ``Data/eval/coverage_bank.jsonl``: curated questions in all three
              languages. No point ids; the runner judges a pool of candidates.
``ood``       Questions the assistant must not answer from the corpus, in all
              three languages: general knowledge, other countries' tax, other
              Ugandan agencies, chit-chat.

Each query row names its ``parent``; the answer to it is stored once, in
``gold.jsonl``. Typo and transcript-style copies are not stored:
``eval_retrieval_multilingual.load_queries`` derives them from the paraphrase,
translated and native rows with seeded functions, the same copies on every
load.

**Caveat on the faq set.** Its paraphrases and translations are produced by
Sunflower, the model the production pivot also translates with. A Sunflower
English-to-Luganda-to-English round trip recovers Sunflower's own English
more easily than a person's Luganda, so the translate leg is flattered there.
The ``native`` and ``coverage`` sets are not generated by this script; compare
against them before trusting a faq-set number for Luganda or Swahili.

Every generated query is kept only if it is in the language it claims to be:
``app.query.detect_language`` and the receptionist's word lists
(``lexical_hits``) must both agree. The detector alone accepts a sentence that
opens in Swahili and continues in Luganda, which the first build produced.
Sunflower also translated the prompt's own instruction instead of the question
when the question followed the instruction unlabelled, so the text is labelled
(``English: …`` / ``Luganda:``), the shape ``llm.translate_text`` uses.

Run it inside ``app-api:gpu`` (for the detector) against the GPU stack:

    docker run --rm --network host --user "$(id -u):$(id -g)" -e HOME=/tmp \\
        -e APP_ENV=development -v "$PWD:/src" -w /src \\
        --entrypoint python app-api:gpu scripts/build_retrieval_multilingual_set.py

Generation is greedy, so a rerun over the same index reproduces the file.
"""

from __future__ import annotations

