def _post(url: str, body: dict[str, Any], timeout: float = 120.0) -> dict[str, Any]:
    req = urllib.request.Request(url, data=json.dumps(body).encode(), headers={"content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.load(resp)


def norm_question(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", (text or "").casefold())).strip()


def load_faq_points(qdrant: str, collection: str) -> list[dict[str, Any]]:
    url = f"{qdrant}/collections/{collection}/points/scroll"
    fields = ["source", "question", "answer", "tag", "row_number", "doc_type", "question_lg", "question_sw"]
    points: list[dict[str, Any]] = []
    offset = None
    while True:
        body: dict[str, Any] = {"limit": 1000, "with_payload": fields, "with_vector": False}
        if offset is not None:
            body["offset"] = offset
        page = _post(url, body)["result"]
        for p in page["points"]:
            pl = p.get("payload") or {}
            if str(pl.get("source", "")).endswith("_faqs.csv") and pl.get("question") and pl.get("answer"):
                points.append({"id": str(p["id"]), **pl})
        offset = page.get("next_page_offset")
        if not offset:
            return points


def chat(llm: str, model: str, system: str, user: str, *, max_tokens: int = 200) -> str:
    body = {
        "model": model,
        "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        "temperature": 0.0,
        "max_tokens": max_tokens,
    }
    for attempt in range(3):
        try:
            out = _post(f"{llm}/chat/completions", body)
            text = out["choices"][0]["message"]["content"] or ""
            return clean_generation(text)
        except Exception:  # noqa: BLE001 — retried, then surfaced as empty
            time.sleep(2 * (attempt + 1))
    return ""


def clean_generation(text: str) -> str:
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()
    first = next((line.strip() for line in text.splitlines() if line.strip()), "")
    first = re.sub(r"^(question|translation|rewritten question|answer)\s*:\s*", "", first, flags=re.I)
    return first.strip().strip('"').strip("“”").strip()


def plausible(source: str, generated: str) -> bool:
    """Rejects empty output, an answer instead of a question, or a runaway."""
    if not generated or _LEAK.search(generated) or _LOOP.search(generated):
        return False
    ratio = len(generated) / max(1, len(source))
    return 0.35 <= ratio <= 3.0 and len(generated) <= 400


def in_language(text: str, lang: str) -> bool:
    """The detector and the word lists both put *text* in *lang*."""
    if detect_language(text) != lang:
        return False
    hits = lexical_hits(text)
    if lang == "en":
        return hits["en"] >= 2 and hits["lg"] == 0 and hits["sw"] == 0
    other = "sw" if lang == "lg" else "lg"
    return hits[lang] >= 1 and hits[lang] > hits[other]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--qdrant", default="http://127.0.0.1:6333")
    ap.add_argument("--collection", default="ura_knowledge_base_jsonl_active")
    ap.add_argument("--llm", default="http://127.0.0.1:8011/v1")
    ap.add_argument("--model", default="Sunbird/Sunflower-14B-FP8")
    ap.add_argument("--per-file", type=int, default=3)
    ap.add_argument("--workers", type=int, default=16)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    points = load_faq_points(args.qdrant, args.collection)
    gold_by_question: dict[str, list[str]] = {}
    for p in points:
        gold_by_question.setdefault(norm_question(p["question"]), []).append(p["id"])
    print(f"faq points {len(points)}; distinct questions {len(gold_by_question)}", file=sys.stderr)

    by_file: dict[str, list[dict[str, Any]]] = {}
    for p in points:
        by_file.setdefault(p["source"], []).append(p)
    sample: list[dict[str, Any]] = []
    for source in sorted(by_file):
        seen: set[str] = set()
        for p in sorted(by_file[source], key=lambda r: stable_rank(r["id"])):
            key = norm_question(p["question"])
            if key in seen or len(key.split()) < 3:
                continue
            seen.add(key)
            sample.append(p)
            if len(seen) >= args.per_file:
                break
    print(f"sampled {len(sample)} rows from {len(by_file)} files", file=sys.stderr)

    rejected: list[str] = []

    def generate(task: tuple[str, str, str, tuple[str, ...], dict[str, str], str]) -> tuple[str, str]:
        """First prompt whose output is plausible and in *lang*; "" when none is."""
        key, system, lang, prompts, fields, source = task
        last = ""
        for prompt in prompts:
            out = chat(args.llm, args.model, system, prompt.format(**fields))
            last = out
            if plausible(source, out) and in_language(out, lang) and out.casefold() != source.casefold():
                return key, out
        rejected.append(f"{key}: {last[:90]!r}")
        return key, ""

    def run(tasks: list[tuple[str, str, str, tuple[str, ...], dict[str, str], str]]) -> dict[str, str]:
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            return dict(pool.map(generate, tasks))

    para = run([
        (p["id"], ENGLISH_SYSTEM, "en", PARAPHRASE_PROMPTS,
         {"topic": str(p.get("tag") or "tax").replace("_", " "), "question": p["question"]}, p["question"])
        for p in sample
    ])
    rows: list[dict[str, Any]] = []
    english = {p["id"]: para.get(p["id"]) or p["question"] for p in sample}

    tasks: list[tuple[str, str, str, tuple[str, ...], dict[str, str], str]] = []
    for p in sample:
        text = english[p["id"]]
        for lang, name in LANG_NAME.items():
            fields = {"language": name, "text": text}
            tasks.append((f"{p['id']}|{lang}|mt", SUNFLOWER_SYSTEM, lang, TRANSLATE_PROMPTS, fields, text))
            tasks.append((f"{p['id']}|{lang}|cs", SUNFLOWER_SYSTEM, lang, CODESWITCH_PROMPTS, fields, text))
    for i, (_, question) in enumerate(OOD_EN):
        for lang, name in LANG_NAME.items():
            tasks.append((f"ood{i}|{lang}|mt", SUNFLOWER_SYSTEM, lang, TRANSLATE_PROMPTS,
                          {"language": name, "text": question}, question))
    generated = run(tasks)

    # The answer to each question lives once, in gold.jsonl, keyed by parent.
    gold: dict[str, dict[str, Any]] = {}
    for p in sample:
        gold[p["id"]] = {
            "parent": p["id"], "gold_ids": gold_by_question[norm_question(p["question"])],
            "gold_question": p["question"], "gold_answer": p["answer"], "source": p["source"], "tag": p.get("tag", ""),
        }
        rows.append({"set": "faq", "parent": p["id"], "id": f"{p['id']}:en_verbatim", "lang": "en",
                     "variant": "verbatim", "query": p["question"], "generator": "corpus"})
        if english[p["id"]] != p["question"]:
            rows.append({"set": "faq", "parent": p["id"], "id": f"{p['id']}:en_paraphrase", "lang": "en",
                         "variant": "paraphrase", "query": english[p["id"]], "generator": "sunflower-14b"})
        for lang in LANG_NAME:
            for kind, variant in (("mt", "translation"), ("cs", "codeswitch")):
                text = generated.get(f"{p['id']}|{lang}|{kind}", "")
                if text:
                    rows.append({"set": "faq", "parent": p["id"], "id": f"{p['id']}:{lang}_{variant}", "lang": lang,
                                 "variant": variant, "query": text, "generator": "sunflower-14b"})

    for p in points:
        for lang in LANG_NAME:
            native = str(p.get(f"question_{lang}") or "").strip()
            if not native:
                continue
            gold.setdefault(p["id"], {
                "parent": p["id"], "gold_ids": gold_by_question[norm_question(p["question"])],
                "gold_question": p["question"], "gold_answer": p["answer"], "source": p["source"],
                "tag": p.get("tag", ""),
            })
            rows.append({"set": "native", "id": f"{p['id']}:{lang}_native", "parent": p["id"], "lang": lang,
                         "variant": "native", "query": native, "generator": "corpus"})

    for line in COVERAGE_BANK.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        item = json.loads(line)
        parent = f"cov:{item['id']}"
        for lang, question in (item.get("question") or {}).items():
            if lang in ("en", "lg", "sw") and question:
                gold.setdefault(parent, {
                    "parent": parent, "gold_ids": [], "gold_question": item["question"].get("en", ""),
                    "expect_any": item.get("expect_any", []), "domain": item.get("domain", ""),
                })
                rows.append({"set": "coverage", "id": f"{parent}:{lang}", "parent": parent, "lang": lang,
                             "variant": "curated", "query": question, "generator": "coverage_bank"})

    for i, (category, question) in enumerate(OOD_EN):
        gold[f"ood{i}"] = {"parent": f"ood{i}", "gold_ids": []}
        rows.append({"set": "ood", "id": f"ood{i}:en", "parent": f"ood{i}", "lang": "en", "variant": category,
                     "query": question, "generator": "hand"})
        for lang in LANG_NAME:
            text = generated.get(f"ood{i}|{lang}|mt", "")
            if text:
                rows.append({"set": "ood", "id": f"ood{i}:{lang}", "parent": f"ood{i}", "lang": lang,
                             "variant": category, "query": text, "generator": "sunflower-14b"})

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    out.with_name("gold.jsonl").write_text(
        "".join(json.dumps(g, ensure_ascii=False) + "\n" for g in gold.values()), encoding="utf-8")
    counts: dict[str, int] = {}
    for row in rows:
        key = f"{row['set']}/{row['lang']}"
        counts[key] = counts.get(key, 0) + 1
    print(json.dumps({"rows": len(rows), "by_set_lang": counts, "rejected": len(rejected)}, indent=1), file=sys.stderr)
    for line in rejected:
        print("  rejected:", line, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
