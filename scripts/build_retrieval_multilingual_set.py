from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
# The repo root too: detect_language imports ml.scripts.lang_id, and without it
# falls back to a character heuristic that mis-detects Ugandan languages.
sys.path[:0] = [str(ROOT / "App" / "backend"), str(ROOT)]
from app.query import detect_language  # noqa: E402
