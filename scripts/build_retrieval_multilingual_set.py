from eval_retrieval_multilingual import stable_rank  # noqa: E402  (this directory)

OUT = ROOT / "evals" / "retrieval_multilingual" / "queries.jsonl"
COVERAGE_BANK = ROOT / "Data" / "eval" / "coverage_bank.jsonl"

LANG_NAME = {"lg": "Luganda", "sw": "Swahili"}

# Sunflower's documented persona, for translation only. Under it the model
# answered an English paraphrase request in Luganda, so paraphrasing uses a
# plain English-only system prompt instead.
SUNFLOWER_SYSTEM = (
    "You are Sunflower, a multilingual assistant made by Sunbird AI who understands "
    "all Ugandan languages. You specialise in accurate translations, explanations, "
    "summaries and other cross-lingual tasks."
)
ENGLISH_SYSTEM = "You are a careful English editor. You always reply in English."

PARAPHRASE_PROMPTS = (
    "Paraphrase the English question below in plain everyday English, the way an "
    "ordinary Ugandan taxpayer would type it to a help-desk chatbot. Keep the meaning. "
    "Avoid the official wording and rare technical terms where an everyday word "
    "exists; common acronyms (URA, TIN, VAT, PAYE, EFRIS) are fine. If the question "
    "relies on a topic it does not name, name it (topic: {topic}). Do not answer it."
    "\n\nOriginal question: {question}\nParaphrased question:",
    "Reword this question in simple English as a member of the public would ask it. "
    "Same meaning, different words; mention the topic ({topic}) if the question "
    "leaves it out. Write only the reworded question in English."
    "\n\nQuestion: {question}\nReworded question:",
)

TRANSLATE_PROMPTS = (
    "Translate the following English text into {language}. It is a question — "
    "translate the question itself, do not answer it.\n\nEnglish: {text}\n{language}:",
    "Translate into {language}. Write only the {language} question.\n\nEnglish: {text}\n{language}:",
)

CODESWITCH_PROMPTS = (
    "Translate the following English question into everyday spoken {language}, as "
    "people in Uganda say it, keeping the English words for tax terms where people "
    "normally would. Translate the question itself, do not answer it."
    "\n\nEnglish: {text}\n{language} (spoken):",
)

_LEAK = re.compile(
    r"translat|tafsiri|kivvuunul|vvuunul|swali lenyewe|do not answer|usilijibu|tokyaddamu|tokiddamu|"
    r"reply with|paraphras|reworded",
    re.I,
)
_LOOP = re.compile(r"\b(\w+)(?:\W+\1\b){3,}", re.I)

